// Generates the taskbar "answer ready" badge (green circle with a white check, 32×32 PNG) as base64 for src/main/taskbar-badge.ts.
import fs from 'node:fs';
import zlib from 'node:zlib';

const N = 32;
const px = Buffer.alloc(N * N * 4);
// distance from point p to segment ab
const seg = (x, y, ax, ay, bx, by) => {
  const dx = bx - ax, dy = by - ay;
  const t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(x - ax - t * dx, y - ay - t * dy);
};
for (let y = 0; y < N; y++)
  for (let x = 0; x < N; x++) {
    let r = 0, g = 0, b = 0, a = 0;
    // 4×4 supersampling for smooth edges
    for (let sy = 0; sy < 4; sy++)
      for (let sx = 0; sx < 4; sx++) {
        const fx = x + (sx + 0.5) / 4, fy = y + (sy + 0.5) / 4;
        if (Math.hypot(fx - 16, fy - 16) > 15.5) continue;
        const check = Math.min(seg(fx, fy, 8.5, 16.5, 13.5, 21.5), seg(fx, fy, 13.5, 21.5, 23.5, 10.5)) < 2.1;
        if (check) (r += 255), (g += 255), (b += 255);
        else (r += 46), (g += 160), (b += 67);
        a += 255;
      }
    const i = (y * N + x) * 4;
    const n = a / 255 || 1;
    px[i] = r / n;
    px[i + 1] = g / n;
    px[i + 2] = b / n;
    px[i + 3] = a / 16;
  }

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc = (buf) => {
  let c = 0xffffffff;
  for (const byte of buf) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const c = Buffer.alloc(4);
  c.writeUInt32BE(crc(td));
  return Buffer.concat([len, td, c]);
};
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(N, 0);
ihdr.writeUInt32BE(N, 4);
ihdr[8] = 8; // bit depth
ihdr[9] = 6; // RGBA
const raw = Buffer.concat(Array.from({ length: N }, (_, y) => Buffer.concat([Buffer.from([0]), px.subarray(y * N * 4, (y + 1) * N * 4)])));
const png = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);

fs.writeFileSync(
  'src/main/taskbar-badge.ts',
  `// Generated by scripts/gen-done-badge.mjs — green circle with a white check, 32×32.\nexport const DONE_BADGE_PNG = '${png.toString('base64')}';\n`,
);
if (process.argv[2]) fs.writeFileSync(process.argv[2], png);
console.log('ok', png.length, 'bytes');
